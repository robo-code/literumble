#!/usr/bin/env python3
"""Regenerate deploy/nginx-cloud-ranges.conf from the providers' published IP lists.

Each provider becomes one shared nginx rate-limit bucket, so scrapers rotating
across a cloud's IPs can't dodge the per-IP limit. Run occasionally; ranges drift.
"""
import csv, io, ipaddress, json, os, re, urllib.request


def get(url):
    req = urllib.request.Request(url, headers={"User-Agent": "literumble-ranges"})
    return urllib.request.urlopen(req, timeout=60).read().decode()


def first_column(text):
    return [r[0] for r in csv.reader(io.StringIO(text)) if r and not r[0].startswith("#")]


def gcp():
    return [p.get("ipv4Prefix") or p["ipv6Prefix"]
            for p in json.loads(get("https://www.gstatic.com/ipranges/cloud.json"))["prefixes"]]


def aws():
    d = json.loads(get("https://ip-ranges.amazonaws.com/ip-ranges.json"))
    return [p["ip_prefix"] for p in d["prefixes"]] + [p["ipv6_prefix"] for p in d["ipv6_prefixes"]]


def azure():
    # The JSON URL changes weekly; scrape it from the download page.
    page = get("https://www.microsoft.com/en-us/download/details.aspx?id=56519")
    url = re.search(r'https://download\.microsoft\.com/[^"]*ServiceTags_Public[^"]*\.json', page).group(0)
    tags = json.loads(get(url))["values"]
    return next(t for t in tags if t["name"] == "AzureCloud")["properties"]["addressPrefixes"]


def oracle():
    d = json.loads(get("https://docs.oracle.com/en-us/iaas/tools/public_ip_ranges.json"))
    return [c["cidr"] for r in d["regions"] for c in r["cidrs"]]


PROVIDERS = {
    "gcp": gcp,
    "aws": aws,
    "azure": azure,
    "oracle": oracle,
    "digitalocean": lambda: first_column(get("https://digitalocean.com/geo/google.csv")),
    "linode": lambda: first_column(get("https://geoip.linode.com/")),
    "vultr": lambda: first_column(get("https://geofeed.constant.com/?text")),
}


def main():
    out = ["# Generated by deploy/gen_cloud_ranges.py -- do not edit by hand."]
    seen = set()
    for name, fetch in PROVIDERS.items():
        nets = sorted({ipaddress.ip_network(p.strip(), strict=False) for p in fetch()},
                      key=lambda n: (n.version, n))
        v4 = ipaddress.collapse_addresses(n for n in nets if n.version == 4)
        v6 = ipaddress.collapse_addresses(n for n in nets if n.version == 6)
        rows = [n for n in [*v4, *v6] if n not in seen]  # exact dupes make nginx warn
        seen.update(rows)
        out.append(f"# {name}: {len(rows)} prefixes")
        out += [f"{n} {name};" for n in rows]
        print(name, len(rows))
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "nginx-cloud-ranges.conf")
    with open(path, "w") as f:
        f.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
